// Generates src/components/brand/brand-logos.ts from @lobehub/icons-static-svg (AI brands, MIT)
// and simple-icons (CC0). Run: node scripts/build-logos.mjs
import fs from "node:fs";
import path from "node:path";

const nm = path.resolve("node_modules");
const lobeDir = path.join(nm, "@lobehub", "icons-static-svg", "icons");
const siDir = path.join(nm, "simple-icons", "icons");
const siData = JSON.parse(fs.readFileSync(path.join(nm, "simple-icons", "data", "simple-icons.json"), "utf8"));
const siList = Array.isArray(siData) ? siData : siData.icons;

// key → [source, file]
const LOBE = {
  claude: "claude-color", anthropic: "anthropic", openai: "openai", gemini: "gemini-color", grok: "grok", xai: "xai",
  deepseek: "deepseek-color", qwen: "qwen-color", kimi: "kimi-color", moonshot: "moonshot", openrouter: "openrouter",
  fal: "fal-color", replicate: "replicate", runway: "runway", luma: "luma", stability: "stability-color",
  elevenlabs: "elevenlabs", bytedance: "bytedance-color", mistral: "mistral-color", meta: "meta-color", figma: "figma-color",
};
const SI = [
  "google", "discord", "apple", "facebook", "github", "supabase", "firebase", "neon", "upstash", "clerk", "stripe",
  "lemonsqueezy", "resend", "posthog", "sentry", "cloudinary", "mapbox", "googlemaps", "algolia", "notion", "airtable",
  "unsplash", "pexels", "nextdotjs", "react", "typescript", "tailwindcss", "vercel", "framer", "radixui", "postgresql",
  "drizzle", "zod", "docker", "cloudflare", "x", "telegram", "ntfy",
];

const out = {};
function parse(svg) {
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 24 24";
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/<title>[\s\S]*?<\/title>/, "")
    .trim();
  return { viewBox, body };
}
function luminance(hex) {
  const n = parseInt(hex, 16);
  const c = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => {
    v /= 255;
    return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}

for (const [key, file] of Object.entries(LOBE)) {
  const p = path.join(lobeDir, `${file}.svg`);
  if (!fs.existsSync(p)) {
    console.warn("missing lobe", file);
    continue;
  }
  const svg = fs.readFileSync(p, "utf8");
  const { viewBox, body } = parse(svg);
  // Mono icons use currentColor; colored ones keep their fills. Prefix ids so gradients never collide.
  const mono = !file.endsWith("-color");
  out[key] = { viewBox, body: body.replace(/id="([^"]+)"/g, `id="${key}-$1"`).replace(/url\(#([^)]+)\)/g, `url(#${key}-$1)`), mono };
}
for (const slug of SI) {
  const p = path.join(siDir, `${slug}.svg`);
  if (!fs.existsSync(p)) {
    console.warn("missing simple-icon", slug);
    continue;
  }
  const meta = siList.find((i) => (i.slug ?? i.title.toLowerCase().replace(/[^a-z0-9]/g, "")) === slug) ?? siList.find((i) => i.title.toLowerCase().replace(/[^a-z0-9]/g, "") === slug);
  const hex = meta?.hex ?? "000000";
  const { viewBox, body } = parse(fs.readFileSync(p, "utf8"));
  const mono = luminance(hex) < 0.06 || luminance(hex) > 0.9;
  out[slug] = { viewBox, body: mono ? body : body.replace("<path ", `<path fill="#${hex}" `), mono };
}

// Google's sign-in guidelines require the four-colour "G".
out.google = {
  viewBox: "0 0 24 24",
  mono: false,
  body:
    '<path fill="#4285F4" d="M22.56 12.25c0-.78-.07-1.53-.2-2.25H12v4.26h5.92c-.26 1.37-1.04 2.53-2.21 3.31v2.77h3.57c2.08-1.92 3.28-4.74 3.28-8.09z"/>' +
    '<path fill="#34A853" d="M12 23c2.97 0 5.46-.98 7.28-2.66l-3.57-2.77c-.98.66-2.23 1.06-3.71 1.06-2.86 0-5.29-1.93-6.16-4.53H2.18v2.84C3.99 20.53 7.7 23 12 23z"/>' +
    '<path fill="#FBBC05" d="M5.84 14.09c-.22-.66-.35-1.36-.35-2.09s.13-1.43.35-2.09V7.07H2.18C1.43 8.55 1 10.22 1 12s.43 3.45 1.18 4.93l2.85-2.22.81-.62z"/>' +
    '<path fill="#EA4335" d="M12 5.38c1.62 0 3.06.56 4.21 1.64l3.15-3.15C17.45 2.09 14.97 1 12 1 7.7 1 3.99 3.47 2.18 7.07l3.66 2.84c.87-2.6 3.3-4.53 6.16-4.53z"/>',
};
for (const [k, v] of Object.entries(out)) {
  if (/<script|\son\w+=|javascript:/i.test(v.body)) throw new Error(`unsafe svg body in ${k}`);
}

const file = `// Generated by scripts/build-logos.mjs — do not edit.
// Sources: @lobehub/icons-static-svg (MIT) and simple-icons (CC0). Trademarks belong to their owners.
export type BrandLogo = { viewBox: string; body: string; mono: boolean };
export const BRAND_LOGOS: Record<string, BrandLogo> = ${JSON.stringify(out, null, 0)};
`;
fs.writeFileSync(path.join("src", "components", "brand", "brand-logos.ts"), file);
console.log(`wrote ${Object.keys(out).length} logos`);
