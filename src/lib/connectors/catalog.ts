/** Client-safe connector catalog. Secrets never appear here. */

export type ConnectorCategory = "media" | "stock" | "ai" | "backend" | "payments" | "analytics" | "maps" | "content" | "design";

export type ConnectorField = { name: string; label: string; secret: boolean; placeholder?: string; optional?: boolean };

export type ConnectorDef = {
  id: string;
  name: string;
  category: ConnectorCategory;
  /** Logo key in the generated brand logo set (see scripts/build-logos.mjs). */
  logo: string | null;
  color: string;
  description: string;
  docsUrl: string;
  fields: ConnectorField[];
  /** Can Forged call it during a build to generate files (generate_media)? */
  media?: ("image" | "video" | "audio")[];
  /** Used by Forged itself, never injected into the project VM. */
  internal?: boolean;
  skill: string;
};

